-- Melke MVP catalog schema
-- PostgreSQL
-- Source-backed starter data only. Compatibility rows are inserted only where
-- the public Melke materials support the relationship clearly.

BEGIN;

CREATE TABLE IF NOT EXISTS profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    mounting_width_mm INTEGER[] NOT NULL,
    -- Order: [frame, sash, mullion], as displayed by Melke.
    air_chambers INTEGER[] NOT NULL,
    thermal_protection NUMERIC(5, 2),
    -- Published "Стеклопакет, мм" values. These are not glass-unit formulas.
    glass_unit_thickness_mm INTEGER[] NOT NULL DEFAULT '{}',
    profile_class VARCHAR(10),
    source_url TEXT,
    CONSTRAINT profiles_mounting_width_nonempty
        CHECK (cardinality(mounting_width_mm) > 0),
    CONSTRAINT profiles_air_chambers_three_parts
        CHECK (cardinality(air_chambers) = 3),
    CONSTRAINT profiles_air_chambers_positive
        CHECK (0 < ALL(air_chambers)),
    CONSTRAINT profiles_thermal_protection_nonnegative
        CHECK (thermal_protection IS NULL OR thermal_protection >= 0)
);

CREATE TABLE IF NOT EXISTS glass_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    chambers_count SMALLINT,
    is_heat_saving BOOLEAN NOT NULL DEFAULT FALSE,
    description TEXT,
    source_url TEXT,
    CONSTRAINT glass_units_chambers_count_valid
        CHECK (chambers_count IS NULL OR chambers_count BETWEEN 1 AND 3)
);

CREATE TABLE IF NOT EXISTS laminations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    coating_type VARCHAR(30) NOT NULL,
    manufacturer VARCHAR(120),
    -- Supported side selections from the calculator: inside and/or outside.
    side_options TEXT[] NOT NULL DEFAULT ARRAY['inside', 'outside'],
    source_url TEXT,
    CONSTRAINT laminations_coating_type_valid
        CHECK (coating_type IN ('lamination', 'cool_colours')),
    CONSTRAINT laminations_side_options_valid
        CHECK (side_options <@ ARRAY['inside', 'outside']::TEXT[])
);

CREATE TABLE IF NOT EXISTS hardware (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacturer VARCHAR(120) NOT NULL,
    model VARCHAR(120),
    description TEXT,
    source_url TEXT,
    CONSTRAINT hardware_manufacturer_model_unique
        UNIQUE (manufacturer, model)
);

-- A window is a concrete saved/standard configuration.
-- Individually measured dimensions may be unknown until the measuring visit.
CREATE TABLE IF NOT EXISTS windows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160),
    profile_id BIGINT NOT NULL REFERENCES profiles(id),
    glass_unit_id BIGINT REFERENCES glass_units(id),
    lamination_id BIGINT REFERENCES laminations(id),
    hardware_id BIGINT REFERENCES hardware(id),
    width_mm INTEGER,
    height_mm INTEGER,
    shape VARCHAR(60),
    number_of_leaves SMALLINT,
    opening_configuration TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    source_url TEXT,
    CONSTRAINT windows_width_positive
        CHECK (width_mm IS NULL OR width_mm > 0),
    CONSTRAINT windows_height_positive
        CHECK (height_mm IS NULL OR height_mm > 0),
    CONSTRAINT windows_number_of_leaves_positive
        CHECK (number_of_leaves IS NULL OR number_of_leaves > 0)
);

-- Explicit compatibility tables. A row means that the combination has been
-- confirmed by a technical card or an authoritative Melke source.
CREATE TABLE IF NOT EXISTS profile_glass_compatibility (
    profile_id BIGINT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
    glass_unit_id BIGINT NOT NULL REFERENCES glass_units(id) ON DELETE CASCADE,
    notes TEXT,
    source_url TEXT,
    PRIMARY KEY (profile_id, glass_unit_id)
);

CREATE TABLE IF NOT EXISTS profile_lamination_compatibility (
    profile_id BIGINT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
    lamination_id BIGINT NOT NULL REFERENCES laminations(id) ON DELETE CASCADE,
    notes TEXT,
    source_url TEXT,
    PRIMARY KEY (profile_id, lamination_id)
);

CREATE TABLE IF NOT EXISTS profile_hardware_compatibility (
    profile_id BIGINT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
    hardware_id BIGINT NOT NULL REFERENCES hardware(id) ON DELETE CASCADE,
    notes TEXT,
    source_url TEXT,
    PRIMARY KEY (profile_id, hardware_id)
);

